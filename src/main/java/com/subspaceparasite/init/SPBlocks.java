        private static void registerItemBlock(Block block) {
            if (block instanceof BlockHarleskinnSlab) {
                return;
            }
            ItemBlock itemBlock = block == RelayBase || block == RelayMiddle || block == RelayRoof || block == RELAY_CONTROLLER ? new ItemBlockWithTooltip(block) : (block instanceof BlockSlabBase ? new ItemSlabBase(block, (IMetaName)block, ((BlockSlabBase)block).getHalfBlock(), ((BlockSlabBase)block).getDoubleBlock()) : (block instanceof IMetaName ? ((IMetaName)block).getItemBlock() : new ItemBlock(block)));
            ResourceLocation registryName = block.getRegistryName();
            if (itemBlock.getRegistryName() == null) {
                itemBlock.setRegistryName(registryName);
            }
            itemRegistry.register((IForgeRegistryEntry)itemBlock);
        }
